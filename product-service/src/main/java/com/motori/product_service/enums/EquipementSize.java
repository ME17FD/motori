package com.motori.product_service.enums;

/**
 * Clothing size enumeration for equipment items.
 * 
 * Represents standard clothing sizes ranging from extra small to extra extra large.
 * Used to classify equipment such as helmets, jackets, and protective gear.
 */
public enum EquipementSize {
    /** Extra small size */
    XS,
    /** Small size */
    S,  
    /** Medium size */
    M,
    /** Large size */
    L,
    /** Extra large size */
    XL,
    /** Extra extra large size */
    XXL
}
